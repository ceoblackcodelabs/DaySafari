@register.filter
def field_label(field):
    """Human label for a bound form field (falls back to its placeholder / aria-label / name)."""
    attrs = field.field.widget.attrs
    return field.label or attrs.get('placeholder') or attrs.get('aria-label') or field.name.replace('_', ' ').capitalize()
