@register.filter
def lp(path):
    """Prefix a site path with the active language code (the site uses /en/..., /sw/... URLs)."""
    from django.utils.translation import get_language
    if not path or path.startswith(('http', '#')):
        return path
    return f'/{get_language() or "en"}{path}'


@register.inclusion_tag('safaris/partials/form.html', takes_context=True)
def lead_form(context, slug=''):
    """The enquiry form. Works on any page: {% lead_form 'kenya-safaris' %}."""
    import uuid
    from .. import leads
    from ..content import (DESTINATIONS, OFFER_BY_ID, PAGE_BY_SLUG, _ALSO_TRIPS, whatsapp_url)
    request = context['request']
    page = PAGE_BY_SLUG.get(slug) or PAGE_BY_SLUG['']
    dest_key = page['destination']
    selected = OFFER_BY_ID.get(request.GET.get('trip', ''))
    form_destination = dest_key or ''
    if selected and (not dest_key or selected['destination'] == dest_key or dest_key in selected['also']
                     or selected['destination'] in _ALSO_TRIPS.get(dest_key, [])):
        form_destination = dest_key or selected['destination']
    else:
        selected = None
    origin = f'{request.scheme}://{request.get_host()}'
    return {
        'request': request, 'csrf_token': context.get('csrf_token'), 'page': page, 'selected': selected,
        'form_destination': form_destination, 'form_dest': DESTINATIONS.get(form_destination),
        'form_questions': DESTINATIONS[form_destination]['questions'] if form_destination else [],
        'select_options': [d for d in DESTINATIONS.values() if d['menu']] + [DESTINATIONS[k] for k in ('cruises', 'hotels', 'services')],
        'questions_json': {k: d['questions'] for k, d in DESTINATIONS.items()}, 'months': leads.next_months(),
        'submission_id': uuid.uuid4(), 'whatsapp': whatsapp_url(origin, page),
    }


@register.simple_tag
def stars(n, size=14):
    """Five stars, the first n filled."""
    try:
        n = max(0, min(5, int(n)))
    except (TypeError, ValueError):
        n = 0
    star = ICONS['star']
    out = ''.join(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" '
        f'fill="{"currentColor" if i < n else "none"}" stroke="currentColor" stroke-width="2" stroke-linejoin="round" '
        f'class="{"" if i < n else "off"}" aria-hidden="true">{star}</svg>' for i in range(5))
    return mark_safe(f'<span class="stars" role="img" aria-label="{n} out of 5 stars">{out}</span>')


