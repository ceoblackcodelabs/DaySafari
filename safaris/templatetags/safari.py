@register.simple_tag
def icon(name, size=16, cls=''):
    return mark_safe(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"'
        f'{f" class={chr(34)}{cls}{chr(34)}" if cls else ""}>{ICONS.get(name, "")}</svg>')


_mtimes = {}


@register.simple_tag
def asset(path):
    """Static URL stamped with the file's mtime, so it can be cached for a year."""
    if path not in _mtimes or settings.DEBUG:
        for base in settings.STATICFILES_DIRS:
            f = Path(base) / path
            if f.exists():
                _mtimes[path] = int(f.stat().st_mtime)
                break
        else:
            _mtimes[path] = 0
    return f'{static(path)}?v={_mtimes[path]}'


@register.simple_tag
def photo(name, hero=False, cls=''):
    info = content.CREDITS[name]
    w, h = info['dimensions']
    card = info.get('card_dimensions')
    srcset = ''
    if card and card[0] < w:
        srcset = format_html(' srcset="{} {}w, {} {}w"', asset(f'images/{name}-card.webp'), card[0], asset(f'images/{name}.webp'), w)
    src = asset(f'images/{name}.webp' if hero else f'images/{name}-card.webp')
    return format_html(
        '<img{} src="{}"{} sizes="{}" alt="{}" width="{}" height="{}" loading="{}" decoding="async"{}>',
        format_html(' class="{}"', cls) if cls else '', src, srcset,
        '100vw' if hero else '(max-width: 700px) 100vw, 50vw', info['caption'], w, h,
        'eager' if hero else 'lazy', mark_safe(' fetchpriority="high"') if hero else '')


